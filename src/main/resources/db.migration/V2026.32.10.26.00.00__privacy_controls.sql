-- Additive privacy controls. No existing account or business history is deleted.
ALTER TABLE fidelity.customers
    ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN token_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN privacy_key UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN profile_updated_at TIMESTAMPTZ,
    ADD COLUMN push_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN push_notice_version VARCHAR(80),
    ADD COLUMN push_updated_at TIMESTAMPTZ;
CREATE UNIQUE INDEX uq_customer_privacy_key ON fidelity.customers(privacy_key);
ALTER TABLE core.staff_users
    ADD COLUMN privacy_key UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN privacy_officer BOOLEAN NOT NULL DEFAULT FALSE;
CREATE UNIQUE INDEX uq_staff_privacy_key ON core.staff_users(privacy_key);

CREATE TABLE ops.privacy_requests (
    id UUID PRIMARY KEY,
    subject_type VARCHAR(20) NOT NULL CHECK (subject_type IN ('CUSTOMER','STAFF')),
    subject_id BIGINT NOT NULL,
    subject_key UUID NOT NULL,
    type VARCHAR(40) NOT NULL,
    scope VARCHAR(20) NOT NULL CHECK (scope IN ('ACCOUNT','MERCHANT')),
    merchant_id BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',
    details VARCHAR(1000),
    assigned_staff_id BIGINT,
    response VARCHAR(2000),
    decision_ref VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    due_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK ((scope='ACCOUNT' AND merchant_id IS NULL) OR (scope='MERCHANT' AND merchant_id IS NOT NULL))
);
CREATE INDEX idx_privacy_request_subject ON ops.privacy_requests(subject_type,subject_key,created_at);
CREATE INDEX idx_privacy_request_status ON ops.privacy_requests(status,created_at);

CREATE TABLE ops.privacy_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID REFERENCES ops.privacy_requests(id) ON DELETE CASCADE,
    subject_type VARCHAR(20) NOT NULL,
    subject_key UUID NOT NULL,
    actor_id BIGINT,
    event VARCHAR(50) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_privacy_event_subject ON ops.privacy_events(subject_type,subject_key,id);

CREATE TABLE ops.privacy_holds (
    id UUID PRIMARY KEY,
    subject_type VARCHAR(20) NOT NULL CHECK (subject_type IN ('CUSTOMER','STAFF')),
    subject_key UUID NOT NULL,
    reason_code VARCHAR(60) NOT NULL,
    evidence_ref VARCHAR(200) NOT NULL,
    created_by BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    review_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    released_by BIGINT,
    release_ref VARCHAR(200)
);
CREATE INDEX idx_privacy_hold_subject ON ops.privacy_holds(subject_type,subject_key) WHERE active;

-- Minimal append-only reconciliation journal. Keep an encrypted copy outside the
-- restored backup before allowing production traffic; a DB-local copy is not enough.
CREATE TABLE ops.privacy_effects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID,
    subject_type VARCHAR(20) NOT NULL,
    subject_id BIGINT NOT NULL,
    subject_key UUID NOT NULL,
    action VARCHAR(40) NOT NULL,
    merchant_id BIGINT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_privacy_effect_subject ON ops.privacy_effects(subject_type,subject_key,id);

CREATE TABLE ops.privacy_replayed_effects (
    origin VARCHAR(80) NOT NULL,
    effect_id BIGINT NOT NULL,
    digest VARCHAR(64) NOT NULL,
    replayed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY(origin,effect_id)
);

CREATE TABLE ops.privacy_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_key UUID NOT NULL,
    purpose VARCHAR(40) NOT NULL CHECK (purpose='LOYALTY_PUSH'),
    enabled BOOLEAN NOT NULL,
    notice_version VARCHAR(80),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_privacy_preference_subject ON ops.privacy_preferences(subject_key,id);
